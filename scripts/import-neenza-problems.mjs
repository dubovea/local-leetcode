import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { convertNeenzaDataset } from "./lib/neenza-converter.mjs";

const SOURCE_URL = "https://raw.githubusercontent.com/neenza/leetcode-problems/master/merged_problems.json";
const OUTPUT = new URL("../src/entities/problem/model/generatedNeenzaProblems.ts", import.meta.url);

async function readDataset(sourceArg) {
  if (sourceArg) {
    const filePath = resolve(process.cwd(), sourceArg);
    const raw = await readFile(filePath, "utf-8");
    return JSON.parse(raw);
  }

  const response = await fetch(SOURCE_URL);

  if (!response.ok) {
    throw new Error(`Failed to download ${SOURCE_URL}: ${response.status} ${response.statusText}`);
  }

  return response.json();
}

function renderTs(problems) {
  return `import type { Problem } from "./types";\n\n// Generated by \`npm run import:neenza\`. Do not edit manually.\nexport const generatedNeenzaProblems: Problem[] = ${JSON.stringify(problems, null, 2)};\n`;
}

const sourceArg = process.argv[2];
const dataset = await readDataset(sourceArg);
const { problems, skippedCount } = convertNeenzaDataset(dataset);

await writeFile(OUTPUT, renderTs(problems));

console.log(`Imported ${problems.length} problems into ${fileURLToPath(OUTPUT)}`);

if (skippedCount > 0) {
  console.log(`Skipped ${skippedCount} invalid items`);
}
